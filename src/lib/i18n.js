const DICTIONARIES = { zh, en };

function detectInitialLang() {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (SUPPORTED_LANGS.includes(stored)) return stored;
  } catch {
    // localStorage may be unavailable
  }
  const param = new URLSearchParams(window.location.search).get('lang');
  if (SUPPORTED_LANGS.includes(param)) return param;
  return 'zh';
}

let currentLang = detectInitialLang();
const listeners = new Set();

document.documentElement.lang = currentLang === 'zh' ? 'zh-CN' : 'en';

function emit() {
  listeners.forEach((listener) => listener());
}

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang) || lang === currentLang) return;
  currentLang = lang;
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // ignore persistence failures
  }
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  emit();
}

function lookup(lang, key) {
  return key.split('.').reduce((node, part) => node?.[part], DICTIONARIES[lang]);
}

function interpolate(template, vars) {
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    vars && vars[name] != null ? String(vars[name]) : match);
}

export function translate(key, vars, lang = currentLang) {
  const value = lookup(lang, key) ?? lookup('zh', key);
  if (typeof value === 'string') return interpolate(value, vars);
  return value ?? key;
}

export function useI18n() {
  const lang = useSyncExternalStore(
    (callback) => {
      listeners.add(callback);
      return () => listeners.delete(callback);
    },
    getLang,
  );
  return {
    lang,
    setLang,
    t: (key, vars) => translate(key, vars, lang),
  };
}

/** Location/node display name for the current language (falls back to Chinese). */
export function localizedName(item, lang = currentLang) {
  if (!item) return '';
  return lang === 'en' && item.en ? item.en : item.name;
}
